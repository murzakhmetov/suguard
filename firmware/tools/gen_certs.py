"""Generate firmware/suguard/src/certs.h with the root CAs used for Firebase.

    python firmware/tools/gen_certs.py

*.firebasedatabase.app is served with Google Trust Services certificates.
The roots are copied from the system trust store of the machine running this
script (e.g. the ca-certificates package), so nothing is downloaded.
"""
from pathlib import Path

ROOTS = ["GTS_Root_R1", "GTS_Root_R3", "GTS_Root_R4"]
STORE = Path("/etc/ssl/certs")
OUT = Path(__file__).resolve().parents[1] / "suguard" / "src" / "certs.h"


def main():
    pems = []
    for name in ROOTS:
        pem = (STORE / f"{name}.pem").read_text().strip()
        assert pem.startswith("-----BEGIN CERTIFICATE-----") and pem.endswith("-----END CERTIFICATE-----"), name
        pems.append(f"// {name.replace('_', ' ')}\n" + "\n".join(f'    "{line}\\n"' for line in pem.splitlines()))
    OUT.write_text(
        "// GENERATED by firmware/tools/gen_certs.py - do not edit.\n"
        "// Root certificates of Google Trust Services (valid until 2036), used to verify\n"
        "// the TLS connection to the Firebase Realtime Database.\n"
        "#pragma once\n\n"
        "static const char SG_ROOT_CAS[] =\n" + "\n".join(pems) + ";\n")
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
